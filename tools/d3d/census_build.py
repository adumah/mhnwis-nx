#!/usr/bin/env python3
"""Direct3D census build (diagnostic only): a counting hook on every function of an address range, to identify the
XDK's Direct3D functions by how often the game calls them (Swap once a frame, draws hundreds of times, CreateDevice
once). The idea of sa2-nx's tools/d3d/d3d_census_build.py, for the classic codegen: each generated function is a weak
alias, so REX_HOOK_RAW(sub_X) replaces it for direct and indirect calls alike.

    tools/d3d/census_build.py [--lo 0x8264E000] [--hi 0x82698000]
    tools/build_pc.sh with the census: MHNWIS_EXTRA_SOURCES=out/census/d3d_census.cpp (see below)

Writes out/census/d3d_census.cpp. While the game runs it writes out/pc/census.csv every 2 s: seconds since start,
then the running call count of every function that was called at least once ("addr:count" pairs).
Build with it:   cmake -S app -B out/pc -DMHNWIS_EXTRA_SOURCES=$PWD/out/census/d3d_census.cpp && tools/build_pc.sh
Build without:   cmake -S app -B out/pc -DMHNWIS_EXTRA_SOURCES= && tools/build_pc.sh
"""
import argparse
import glob
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
GEN = os.path.join(ROOT, 'app', 'generated', 'default')
OUT = os.path.join(ROOT, 'out', 'census', 'd3d_census.cpp')

ap = argparse.ArgumentParser()
ap.add_argument('--lo', type=lambda s: int(s, 16), default=0x8264E000)
ap.add_argument('--hi', type=lambda s: int(s, 16), default=0x82698000)
a = ap.parse_args()

funcs = set()
for path in glob.glob(os.path.join(GEN, 'mhnwis_recomp.*.cpp')):
    for m in re.finditer(r'^DEFINE_REX_FUNC\(sub_([0-9A-F]{8})\)', open(path, errors='replace').read(), re.M):
        if a.lo <= int(m.group(1), 16) < a.hi:
            funcs.add(m.group(1))
funcs = sorted(funcs)

os.makedirs(os.path.dirname(OUT), exist_ok=True)
with open(OUT, 'w') as o:
    o.write(f'''// Generated by tools/d3d/census_build.py: the Direct3D census (diagnostic only, never in a release build).
// {len(funcs)} functions, 0x{a.lo:08X}-0x{a.hi:08X}.

#include <atomic>
#include <chrono>
#include <cstdint>
#include <cstdio>
#include <string>
#include <thread>

#include <rex/filesystem.h>
#include <rex/hook.h>
#include <rex/ppc.h>

namespace {{
constexpr uint32_t kAddresses[] = {{
''')
    for i in range(0, len(funcs), 8):
        o.write('    ' + ' '.join(f'0x{f}u,' for f in funcs[i:i + 8]) + '\n')
    o.write(f'''}};
constexpr size_t kCount = {len(funcs)};
std::atomic<uint64_t> g_calls[kCount];

struct Writer {{
  Writer() {{
    std::thread([] {{
      const auto start = std::chrono::steady_clock::now();
      const auto path = rex::filesystem::GetExecutableFolder() / "census.csv";
      FILE* f = std::fopen(path.string().c_str(), "w");
      if (!f) return;
      for (int tick = 1;; ++tick) {{
        std::this_thread::sleep_until(start + std::chrono::seconds(2 * tick));
        std::fprintf(f, "%d", 2 * tick);
        for (size_t i = 0; i < kCount; ++i) {{
          const uint64_t n = g_calls[i].load(std::memory_order_relaxed);
          if (n) std::fprintf(f, ",%08X:%llu", kAddresses[i], static_cast<unsigned long long>(n));
        }}
        std::fputc('\\n', f);
        std::fflush(f);
      }}
    }}).detach();
  }}
}} g_writer;
}}  // namespace

#define CENSUS_HOOK(index, name)                                      \\
  extern "C" void __imp__##name(PPCContext& __restrict, uint8_t*);   \\
  REX_HOOK_RAW(name) {{                                                \\
    g_calls[index].fetch_add(1, std::memory_order_relaxed);           \\
    __imp__##name(ctx, base);                                         \\
  }}

''')
    for i, f in enumerate(funcs):
        o.write(f'CENSUS_HOOK({i}, sub_{f})\n')
print(f'{len(funcs)} census hooks written to {OUT}')
